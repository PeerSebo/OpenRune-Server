import dev.openrune.definition.dbtables.dbTable
import dev.openrune.definition.util.VarType

internal fun farmingCrops() = dbTable("dbtable.farming_crops", serverOnly = true) {
    column("order", 0, VarType.INT)
    column("key", 1, VarType.STRING)
    column("patch_type", 2, VarType.STRING)
    column("seed", 3, VarType.OBJ)
    column("produce", 4, VarType.OBJ)
    column("level", 5, VarType.INT)
    column("plant_xp_tenths", 6, VarType.INT)
    column("harvest_xp_tenths", 7, VarType.INT)
    column("check_xp_tenths", 8, VarType.INT)
    column("growth_cycles", 9, VarType.INT)
    column("cycle_minutes", 10, VarType.INT)
    column("seeds", 11, VarType.INT)
    column("protection_item", 12, VarType.OBJ)
    column("protection_count", 13, VarType.INT)
    column("sapling", 14, VarType.OBJ)
    column("base_lives", 15, VarType.INT)
    column("produce_capacity", 16, VarType.INT)
    column("regrow_minutes", 17, VarType.INT)
    column("disease_chance", 18, VarType.INT)
    column("save_low", 19, VarType.INT)
    column("save_high", 20, VarType.INT)
    column("pot_seed", 21, VarType.OBJ)
    column("pot_seed_watered", 22, VarType.OBJ)
    column("placed", 23, VarType.BOOLEAN)
    column("waterable", 24, VarType.BOOLEAN)
    column("hespori_denominator", 25, VarType.INT)

    for ((order, crop) in crops.withIndex()) {
        row("dbrow.farming_crop_${crop.key}") {
            column(0, order)
            column(1, crop.key)
            column(2, crop.patchType)
            columnRSCM(3, crop.seed)
            crop.produce?.let { columnRSCM(4, it) }
            column(5, crop.level)
            column(6, crop.plantXpTenths)
            column(7, crop.harvestXpTenths)
            column(8, crop.checkXpTenths)
            column(9, crop.growthCycles)
            column(10, crop.cycleMinutes)
            column(11, crop.seeds)
            crop.protectionItem?.let { columnRSCM(12, it) }
            crop.protectionCount?.let { column(13, it) }
            crop.sapling?.let { columnRSCM(14, it) }
            column(15, crop.baseLives)
            column(16, crop.produceCapacity)
            column(17, crop.regrowMinutes)
            column(18, crop.diseaseChance)
            crop.saveLow?.let { column(19, it) }
            crop.saveHigh?.let { column(20, it) }
            crop.potSeed?.let { columnRSCM(21, it) }
            crop.potSeedWatered?.let { columnRSCM(22, it) }
            column(23, crop.placed)
            crop.waterable?.let { column(24, it) }
            crop.hesporiDenominator?.let { column(25, it) }
        }
    }
}

internal fun farmingSaplings() = dbTable("dbtable.farming_saplings", serverOnly = true) {
    column("key", 0, VarType.STRING)
    column("seed", 1, VarType.OBJ)
    column("level", 2, VarType.INT)
    column("seedling", 3, VarType.OBJ)
    column("watered", 4, VarType.OBJ)
    column("sapling", 5, VarType.OBJ)
    for (crop in crops.filter { it.potSeed != null }) {
        row("dbrow.farming_sapling_${crop.key}") {
            column(0, crop.key)
            columnRSCM(1, crop.seed)
            column(2, crop.level)
            columnRSCM(3, checkNotNull(crop.potSeed))
            columnRSCM(4, checkNotNull(crop.potSeedWatered))
            columnRSCM(5, checkNotNull(crop.sapling))
        }
    }
    val additional = listOf(
        Triple("teak", "teak", 35),
        Triple("mahogany", "mahogany", 55),
        Triple("calquat", "calquat_tree", 72),
        Triple("spirit", "spirit_tree", 83),
        Triple("celastrus", "celastrus_tree", 85),
        Triple("redwood", "redwood_tree", 90),
        Triple("crystal", "crystal_tree", 74),
        Triple("camphor", "camphor", 66),
        Triple("ironwood", "ironwood", 80),
        Triple("rosewood", "rosewood", 92),
    )
    for ((key, seedName, level) in additional) {
        val potName = if (key == "calquat") key else seedName
        row("dbrow.farming_sapling_$key") {
            column(0, key)
            columnRSCM(1, "obj.${seedName}_seed")
            column(2, level)
            columnRSCM(3, "obj.plantpot_${potName}_seed")
            columnRSCM(4, "obj.plantpot_${potName}_seed_watered")
            columnRSCM(5, "obj.plantpot_${potName}_sapling")
        }
    }
}

