private fun DBTableBuilder.visual(
    crop: String,
    band: String,
    anchor: String,
    firstStage: Int = 0,
    vararg stages: String,
) {
    row("dbrow.farming_crop_visual_${crop}_$band") {
        columnRSCM(0, "dbrow.farming_crop_$crop")
        column(1, band)
        columnRSCM(2, anchor)
        column(3, firstStage)
        if (stages.isNotEmpty()) columnRSCM(4, *stages)
    }
}
