internal object ShopkeeperStockTable {
    fun build() = dbTable("dbtable.shopkeeper_stock_profiles", serverOnly = true) {
        column("profile_order", 0, VarType.INT)
        column("key", 1, VarType.STRING)
        column("inventory", 2, VarType.INV)
        column("merchants", 3, VarType.NPC)
        column("name", 4, VarType.STRING)
        column("display_template", 5, VarType.INV)
        column("sell_multiplier", 6, VarType.INT)
        column("buy_multiplier", 7, VarType.INT)
        column("delta", 8, VarType.INT)
        column("all_stock", 9, VarType.BOOLEAN)
        column("items", 10, VarType.OBJ)
        column("counts", 11, VarType.INT)
        column("restock_cycles", 12, VarType.INT)
        column("unsellable", 13, VarType.OBJ)
        for ((order, profile) in profiles.withIndex()) {
            row("dbrow.shopkeeper_stock_" + profile.key.removePrefix("profile.")) {
                val stock = profile.stock
                column(0, order)
                column(1, profile.key)
                columnRSCM(2, profile.inventory)
                columnRSCM(3, *profile.merchants.toTypedArray())
                column(4, stock.name)
                columnRSCM(5, stock.displayTemplate)
                column(6, stock.sellMultiplier)
                column(7, stock.buyMultiplier)
                column(8, stock.delta)
                column(9, stock.allStock)
                columnRSCM(10, *stock.stock.map { it.symbol }.toTypedArray())
                column(11, *stock.stock.map { it.count }.toTypedArray<Any>())
                column(12, *stock.stock.map { it.restockCycles }.toTypedArray<Any>())
                if (stock.unsellableItems.isNotEmpty()) {
                    columnRSCM(13, *stock.unsellableItems.toTypedArray())
                }
            }
        }
    }

