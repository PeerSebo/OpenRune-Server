        column("title", 3, VarType.STRING)
        column("infinite_stock", 4, VarType.BOOLEAN)
        column("allow_selling", 5, VarType.BOOLEAN)
        column("key", 6, VarType.STRING)
        for ((order, binding) in bindings.withIndex()) {
            row("dbrow.shopkeeper_binding_" + binding.merchants.first().removePrefix("npc.")) {
                column(0, order)
                columnRSCM(1, binding.inventory)
                columnRSCM(2, *binding.merchants.toTypedArray())
                column(3, binding.title)
                column(4, binding.infiniteStock)
                column(5, binding.allowSelling)
                column(6, binding.inventory)
            }
        }
    }

